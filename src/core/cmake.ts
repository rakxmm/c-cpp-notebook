import { existsSync, promises as fs } from 'node:fs';
import * as path from 'node:path';
import type { Language } from './assemble';
import {
  failedBuild,
  processOutput,
  writeIfChanged,
  type BuildContext,
  type BuildResult,
} from './build';
import { runProcess } from './process';
import { findCompiler, resolveCMake } from './tools';

const TARGET = 'ccnb_runner';

function quote(value: string): string {
  const normalized = value.replace(/\\/g, '/');
  return `"${normalized.replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
}

export interface WrapperOptions {
  language: Language;
  sources: string[];
  includeDir: string;
  compileArgs: string[];
  linkItems: string[];
  projectRoot?: string;
}

/** Generates the project that builds the notebook, optionally on top of the user's project. */
export function generateWrapper(options: WrapperOptions): string {
  const lines = [
    '# Generated by C/C++ Notebook.',
    'cmake_minimum_required(VERSION 3.16)',
    `project(ccnb_wrapper LANGUAGES ${options.language === 'cpp' ? 'CXX' : 'C'})`,
    // Windows finds a project's DLLs only when they sit next to the executable.
    'set(CMAKE_RUNTIME_OUTPUT_DIRECTORY "${CMAKE_BINARY_DIR}/bin")',
  ];
  if (options.projectRoot) {
    lines.push(`add_subdirectory(${quote(options.projectRoot)} "\${CMAKE_BINARY_DIR}/project")`);
  }
  lines.push(
    `add_executable(${TARGET} ${options.sources.map(quote).join(' ')})`,
    `target_include_directories(${TARGET} PRIVATE ${quote(options.includeDir)})`,
  );
  if (options.compileArgs.length > 0) {
    lines.push(`target_compile_options(${TARGET} PRIVATE ${options.compileArgs.map(quote).join(' ')})`);
  }
  if (options.linkItems.length > 0) {
    lines.push(`target_link_libraries(${TARGET} PRIVATE ${options.linkItems.map(quote).join(' ')})`);
  }
  return `${lines.join('\n')}\n`;
}

export async function buildWithCMake(context: BuildContext): Promise<BuildResult> {
  const { request, compiler, dir, env } = context;
  const tools = request.tools[request.language];
  const compilerDir = path.dirname(compiler);
  const cmakeTools = resolveCMake(request.cmakePath, compilerDir, request.env ?? process.env);

  const sourceDir = path.join(dir, 'src');
  const binaryDir = path.join(dir, 'build');
  const extension = request.language === 'cpp' ? 'cpp' : 'c';
  const sources = [`notebook.${extension}`, `ccnb_runtime.${extension}`];
  const executable = path.join(
    binaryDir,
    'bin',
    process.platform === 'win32' ? `${TARGET}.exe` : TARGET,
  );

  const hasProject =
    request.projectRoot !== undefined && existsSync(path.join(request.projectRoot, 'CMakeLists.txt'));
  const wrapper = generateWrapper({
    language: request.language,
    sources,
    includeDir: request.workingDir,
    compileArgs: tools.compileArgs,
    linkItems: [...request.links, ...tools.linkArgs],
    projectRoot: hasProject ? request.projectRoot : undefined,
  });
  await writeIfChanged(path.join(sourceDir, 'CMakeLists.txt'), wrapper);
  await writeIfChanged(path.join(sourceDir, sources[0]), context.source);
  await writeIfChanged(path.join(sourceDir, sources[1]), context.runtime);

  const options = { cwd: dir, env, signal: request.signal };

  // Only the first run configures. After that the build tool re-runs CMake by itself
  // whenever a CMakeLists.txt changes, including the user's.
  const otherLanguage: Language = request.language === 'cpp' ? 'c' : 'cpp';
  const otherCompiler = findCompiler(
    otherLanguage,
    request.tools[otherLanguage].compiler,
    request.env ?? process.env,
    compilerDir,
  );
  const compilers: Record<string, string | undefined> = {
    [request.language]: compiler,
    [otherLanguage]: otherCompiler,
  };
  const configureArgs = [
    '-S',
    sourceDir,
    '-B',
    binaryDir,
    '-G',
    cmakeTools.generator,
    `-DCMAKE_MAKE_PROGRAM=${cmakeTools.makeProgram}`,
    `-DCMAKE_C_COMPILER=${compilers.c ?? ''}`,
    `-DCMAKE_CXX_COMPILER=${compilers.cpp ?? ''}`,
  ].filter((arg) => !arg.endsWith('='));

  const stampFile = path.join(binaryDir, '.ccnb-configured');
  const stamp = JSON.stringify([cmakeTools, configureArgs]);
  const currentStamp = await fs.readFile(stampFile, 'utf8').catch(() => undefined);
  if (currentStamp !== stamp) {
    const configured = await runProcess(cmakeTools.cmake, configureArgs, options);
    if (configured.code !== 0) {
      return failedBuild(configured, executable);
    }
    await fs.writeFile(stampFile, stamp);
  }

  const built = await runProcess(
    cmakeTools.cmake,
    ['--build', binaryDir, '--target', TARGET],
    options,
  );
  if (built.code !== 0) {
    return failedBuild(built, executable);
  }
  return { ok: true, output: processOutput(built), executable, cancelled: false };
}
