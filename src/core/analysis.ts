import { hoistIncludes, isGlobalCell, type CodeCell } from './assemble';

/** A 0-based line inside a code cell. */
export interface CellLine {
  cell: number;
  line: number;
}

/**
 * The notebook as language tools should see it: the same structure as the compiled
 * program, but without #line directives, which would send tools to files that do not
 * exist, and without run markers, which would show up in completions.
 */
export interface AnalysisProgram {
  source: string;
  /** For each line of `source`, its cell line; undefined for generated lines. */
  origins: (CellLine | undefined)[];
  /** For each cell number, the line of `source` that holds each of its lines. */
  programLines: Map<number, number[]>;
}

export const ANALYSIS_HEADER =
  '/* Generated by C/C++ Notebook for IntelliSense. Edit the notebook; changes here are overwritten. */';

interface ProgramLine {
  text: string;
  origin?: CellLine;
}

export function assembleForAnalysis(cells: CodeCell[]): AnalysisProgram {
  const fileScope: ProgramLine[] = [{ text: ANALYSIS_HEADER }];
  const mainBody: ProgramLine[] = [];

  for (const cell of cells) {
    const lines = cell.source.split(/\r?\n/);
    const tagged = (text: string, line: number): ProgramLine => ({
      text,
      origin: { cell: cell.number, line },
    });
    if (isGlobalCell(lines)) {
      fileScope.push(...lines.map(tagged));
      continue;
    }
    const { hoisted, body } = hoistIncludes(lines);
    const lifted = new Set<number>();
    for (const block of hoisted) {
      block.lines.forEach((text, offset) => {
        const line = block.firstLine - 1 + offset;
        lifted.add(line);
        fileScope.push(tagged(text, line));
      });
    }
    body.forEach((text, line) => {
      if (!lifted.has(line)) {
        mainBody.push(tagged(text, line));
      }
    });
  }

  const all: ProgramLine[] = [
    ...fileScope,
    { text: 'int main(void) {' },
    ...mainBody,
    { text: 'return 0;' },
    { text: '}' },
    { text: '' },
  ];
  const programLines = new Map<number, number[]>();
  all.forEach(({ origin }, index) => {
    if (origin) {
      const lines = programLines.get(origin.cell) ?? [];
      lines[origin.line] = index;
      programLines.set(origin.cell, lines);
    }
  });
  return {
    source: all.map(({ text }) => text).join('\n'),
    origins: all.map(({ origin }) => origin),
    programLines,
  };
}

/**
 * An error can land on a generated line, such as the closing brace of main() after an
 * unbalanced cell. It is caused by the closest cell line before it.
 */
export function nearestOrigin(
  origins: AnalysisProgram['origins'],
  programLine: number,
): CellLine | undefined {
  for (let line = Math.min(programLine, origins.length - 1); line >= 0; line--) {
    const origin = origins[line];
    if (origin) {
      return origin;
    }
  }
  return undefined;
}

export interface LineEdit {
  startLine: number;
  /** Exclusive. */
  endLine: number;
  text: string;
}

/**
 * The smallest whole-line replacement that turns `current` into `wanted`; undefined when
 * they match. Tools get a small change instead of a rewritten file on every keystroke.
 * Line endings are ignored because the editor normalizes them.
 */
export function lineEdit(current: string, wanted: string): LineEdit | undefined {
  const normalized = current.replace(/\r\n/g, '\n');
  if (normalized === wanted) {
    return undefined;
  }
  const oldLines = normalized.split('\n');
  const newLines = wanted.split('\n');
  // Whole-line edits need a line break after the replaced part.
  if (oldLines.at(-1) !== '' || newLines.at(-1) !== '') {
    return { startLine: 0, endLine: oldLines.length, text: wanted };
  }
  // The empty last element stands for the end of the text, so an edit never starts past it.
  let start = 0;
  while (
    start < oldLines.length - 1 &&
    start < newLines.length - 1 &&
    oldLines[start] === newLines[start]
  ) {
    start++;
  }
  let suffix = 0;
  while (
    suffix < oldLines.length - start &&
    suffix < newLines.length - start &&
    oldLines[oldLines.length - 1 - suffix] === newLines[newLines.length - 1 - suffix]
  ) {
    suffix++;
  }
  const inserted = newLines.slice(start, newLines.length - suffix);
  return {
    startLine: start,
    endLine: oldLines.length - suffix,
    text: inserted.map((line) => `${line}\n`).join(''),
  };
}
