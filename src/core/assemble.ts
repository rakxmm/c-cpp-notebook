export type Language = 'c' | 'cpp';

export interface CodeCell {
  /** 1-based position among the notebook's code cells; shown in diagnostics as `cell_N`. */
  number: number;
  source: string;
}

export interface AssembledProgram {
  source: string;
  /** Cells placed outside main(); they produce no runtime output. */
  globalCells: Set<number>;
}

const GLOBAL_MARKER = /^\s*\/\/\s*%global\s*$/;
const INCLUDE = /^\s*#\s*include\b/;
const CONDITIONAL_START = /^\s*#\s*if(n?def)?\b/;
const CONDITIONAL_END = /^\s*#\s*endif\b/;

export const END_OF_MAIN = -1;

function isGlobalCell(lines: string[]): boolean {
  const first = lines.find((line) => line.trim() !== '');
  return first !== undefined && GLOBAL_MARKER.test(first);
}

/** Returns the index just past the #endif that closes the conditional opened at `start`. */
function conditionalEnd(lines: string[], start: number): number {
  let depth = 0;
  for (let i = start; i < lines.length; i++) {
    if (CONDITIONAL_START.test(lines[i])) {
      depth++;
    } else if (CONDITIONAL_END.test(lines[i]) && --depth === 0) {
      return i + 1;
    }
  }
  return lines.length;
}

interface HoistedBlock {
  firstLine: number;
  lines: string[];
}

/**
 * Moves #include directives out of a cell so they end up at file scope. A conditional
 * block containing an include moves as a whole; lifting only the include would drop its
 * guard. Removed lines become blank to keep the cell's line numbers intact.
 */
function hoistIncludes(lines: string[]): { hoisted: HoistedBlock[]; body: string[] } {
  const hoisted: HoistedBlock[] = [];
  const body = [...lines];
  const lift = (start: number, end: number) => {
    hoisted.push({ firstLine: start + 1, lines: lines.slice(start, end) });
    body.fill('', start, end);
  };

  for (let i = 0; i < lines.length; i++) {
    if (INCLUDE.test(lines[i])) {
      lift(i, i + 1);
    } else if (CONDITIONAL_START.test(lines[i])) {
      const end = conditionalEnd(lines, i);
      if (lines.slice(i, end).some((line) => INCLUDE.test(line))) {
        lift(i, end);
      }
      i = end - 1;
    }
  }
  return { hoisted, body };
}

export function assemble(language: Language, cells: CodeCell[]): AssembledProgram {
  const declaration =
    language === 'cpp' ? 'extern "C" void ccnb_mark(int cell);' : 'void ccnb_mark(int cell);';
  const fileScope: string[] = ['/* Generated by C/C++ Notebook. */', declaration];
  const mainBody: string[] = [];
  const globalCells = new Set<number>();

  for (const cell of cells) {
    const lines = cell.source.split(/\r?\n/);
    const fileName = `"cell_${cell.number}"`;
    if (isGlobalCell(lines)) {
      globalCells.add(cell.number);
      fileScope.push(`#line 1 ${fileName}`, ...lines);
      continue;
    }
    const { hoisted, body } = hoistIncludes(lines);
    for (const block of hoisted) {
      fileScope.push(`#line ${block.firstLine} ${fileName}`, ...block.lines);
    }
    mainBody.push(`ccnb_mark(${cell.number});`, `#line 1 ${fileName}`, ...body);
  }

  const source = [
    ...fileScope,
    '#line 1 "ccnb_main"',
    'int main(void) {',
    ...mainBody,
    `ccnb_mark(${END_OF_MAIN});`,
    'return 0;',
    '}',
    '',
  ].join('\n');
  return { source, globalCells };
}

const C_RUNTIME = `#include <stdio.h>
#include <stdlib.h>

static void emit(FILE *stream, const char *nonce, int cell) {
    fflush(stream);
    fprintf(stream, "\\036CCNB:%s:%d\\036", nonce, cell);
    fflush(stream);
}

void ccnb_mark(int cell) {
    const char *nonce = getenv("CCNB_MARKER");
    if (nonce == NULL) {
        return;
    }
    emit(stdout, nonce, cell);
    emit(stderr, nonce, cell);
}
`;

const CPP_RUNTIME = `#include <cstdio>
#include <cstdlib>
#include <iostream>

static void emit(std::FILE *stream, const char *nonce, int cell) {
    std::fflush(stream);
    std::fprintf(stream, "\\036CCNB:%s:%d\\036", nonce, cell);
    std::fflush(stream);
}

extern "C" void ccnb_mark(int cell) {
    const char *nonce = std::getenv("CCNB_MARKER");
    if (nonce == nullptr) {
        return;
    }
    // Streams detached with sync_with_stdio(false) keep their own buffers.
    std::cout.flush();
    std::cerr.flush();
    std::clog.flush();
    emit(stdout, nonce, cell);
    emit(stderr, nonce, cell);
}
`;

/**
 * Lives in its own translation unit so the notebook source needs no includes of ours:
 * a forgotten #include stays a compile error and feature macros such as _GNU_SOURCE
 * still come before the first system header.
 */
export function runtimeSource(language: Language): string {
  return language === 'cpp' ? CPP_RUNTIME : C_RUNTIME;
}
